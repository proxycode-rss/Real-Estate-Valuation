import pandas as pd
s = pd.read_excel('/content/Real estate valuation data set.xlsx')
s.head()

"""### 1. Dataset Information and Statistics
Let's check the column datatypes, missing values, and overall descriptive statistics of the dataset.
"""

# Print summary information of the dataset
s.info()

# Display descriptive statistics
display(s.describe())

"""### 2. Check for Missing Values"""

# Check if there are any missing values in each column
missing_values = s.isnull().sum()
print("Missing values per column:")
print(missing_values)

"""### 3. Visualizing Feature Correlations
Let's plot a correlation heatmap to see which variables are most strongly associated with the house prices.
"""

import matplotlib.pyplot as plt
import seaborn as sns

# Calculate correlation matrix (excluding the index/No column if present)
corr_matrix = s.drop(columns=['No']).corr()

# Generate heatmap
plt.figure(figsize=(10, 8))
sns.heatmap(corr_matrix, annot=True, cmap='coolwarm', fmt='.2f', linewidths=0.5)
plt.title('Correlation Heatmap')
plt.tight_layout()
plt.show()

# Calculate the average house age from the 'X2 house age' column
average_house_age = s['X2 house age'].mean()
print(f"The average house age is {average_house_age:.2f} years.")

"""### 4. Comparing House Prices: Near vs. Far from MRT Station
We'll use **500 meters** as our threshold to segment the properties into two groups:
* **Near MRT:** distance $\le$ 500 meters
* **Far from MRT:** distance $>$ 500 meters
"""

# Define threshold (500 meters)
threshold = 500

# Split the dataset into near and far
near_mrt = s[s['X3 distance to the nearest MRT station'] <= threshold]
far_mrt = s[s['X3 distance to the nearest MRT station'] > threshold]

# Calculate average prices
avg_price_near = near_mrt['Y house price of unit area'].mean()
avg_price_far = far_mrt['Y house price of unit area'].mean()

print(f"Average price for properties NEAR MRT (<= {threshold}m): {avg_price_near:.2f} per unit area (Count: {len(near_mrt)})")
print(f"Average price for properties FAR from MRT (> {threshold}m): {avg_price_far:.2f} per unit area (Count: {len(far_mrt)})")

import matplotlib.pyplot as plt
import seaborn as sns

# Create a categorical column for visualization
s['MRT Proximity'] = s['X3 distance to the nearest MRT station'].apply(
    lambda x: f'Near (<= {threshold}m)' if x <= threshold else f'Far (> {threshold}m)'
)

# Plot the comparison
plt.figure(figsize=(8, 6))
sns.barplot(x='MRT Proximity', y='Y house price of unit area', data=s, estimator='mean', errorbar=None, palette='Set2', hue='MRT Proximity', legend=False)
plt.title('Average House Price by MRT Proximity')
plt.ylabel('Average Price of Unit Area')
plt.xlabel('Proximity to MRT')
plt.grid(axis='y', linestyle='--', alpha=0.7)
plt.show()

"""### 5. Impact of Convenience Stores on House Price
Let's calculate the average house price based on the number of nearby convenience stores (`X4 number of convenience stores`).
"""

# Calculate the average price grouped by the number of convenience stores
store_price_analysis = s.groupby('X4 number of convenience stores')['Y house price of unit area'].agg(['mean', 'count']).reset_index()

# Rename columns for clarity
store_price_analysis.columns = ['Number of Convenience Stores', 'Average House Price', 'Record Count']
display(store_price_analysis)

import matplotlib.pyplot as plt
import seaborn as sns

# Plot the relationship between convenience stores and average price
plt.figure(figsize=(10, 6))
sns.barplot(x='Number of Convenience Stores', y='Average House Price', data=store_price_analysis, palette='viridis', hue='Number of Convenience Stores', legend=False)
plt.title('Average House Price vs. Number of Nearby Convenience Stores')
plt.xlabel('Number of Convenience Stores')
plt.ylabel('Average House Price of Unit Area')
plt.grid(axis='y', linestyle='--', alpha=0.7)
plt.show()

"""### 6. Finding the 10 Highest-Priced Records
Let's sort our dataset by the unit area price in descending order to identify the top 10 most expensive properties.
"""

# Sort by 'Y house price of unit area' in descending order and get the top 10
top_10_expensive = s.sort_values(by='Y house price of unit area', ascending=False).head(10)
display(top_10_expensive)

"""### 7. Missing Values and Duplicates Check
We will summarize our missing values scan and verify if there are any duplicate rows in the dataset.
"""

# 1. Verify missing values again
missing_count = s.isnull().sum().sum()
print(f"Total missing values in the dataset: {missing_count}")

# 2. Check for duplicate rows (excluding the unique identifier 'No' to find true duplicate properties)
duplicate_rows = s.drop(columns=['No']).duplicated().sum()
print(f"Number of duplicate property records (excluding 'No'): {duplicate_rows}")